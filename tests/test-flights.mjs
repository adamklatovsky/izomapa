import assert from 'node:assert/strict';
const store = new Map(); let calls = [];
globalThis.caches = { default: { match: async (k) => store.get(k.url)?.clone(), put: async (k, v) => { store.set(k.url, v); } } };
let ua = null;
globalThis.fetch = async (u, o) => { calls.push(String(u)); ua = o.headers['user-agent']; return new Response('{"ac":[{"hex":"abc","lat":49.6,"lon":18.1}]}', { status: 200 }); };
const { onRequest } = await import('../functions/api/flights.js');
const ask = (q) => onRequest({ request: new Request('http://x/api/flights' + q) });
let r = await ask('?lamin=49.2&lamax=50.0&lomin=17.6&lomax=18.6');
assert.equal(r.status, 200); assert.equal((await r.json()).ac.length, 1);
assert.deepEqual(calls, ['https://api.adsb.lol/v2/point/49.60/18.10/35']);
r = await ask('?lamin=49.2&lamax=50.0&lomin=17.6&lomax=18.6'); assert.equal(r.status, 200); assert.equal(calls.length, 1, 'second ask is served from cache');
assert.equal(ua, 'izomapa-letadla/1.0');
r = await ask('?lamin=x'); assert.equal(r.status, 400); assert.equal(calls.length, 1);
r = await ask('?lamin=40&lamax=50&lomin=17&lomax=18'); assert.equal(r.status, 400, 'příliš velký výřez');
r = await ask('?lamin=40.2&lamax=41.0&lomin=-74.5&lomax=-73.5'); assert.equal(r.status, 400, 'střed mimo Česko a okolí');
assert.equal(calls.length, 1, 'odmítnuté dotazy nejdou na adsb.lol');
globalThis.fetch = async (u) => { calls.push(String(u)); return new Response('busy', { status: 503 }); }; store.clear(); calls = [];
r = await ask('?lamin=49.2&lamax=50.0&lomin=17.6&lomax=18.6'); assert.equal(r.status, 200); assert.deepEqual(await r.json(), { ac: [] }, 'výpadek = prázdný seznam');
r = await ask('?lamin=49.2&lamax=50.0&lomin=17.6&lomax=18.6'); assert.deepEqual(await r.json(), { ac: [] }); assert.equal(calls.length, 1, 'výpadek se cachuje');
globalThis.fetch = async () => { throw new DOMException('timeout', 'TimeoutError'); }; store.clear();
r = await ask('?lamin=49.2&lamax=50.0&lomin=17.6&lomax=18.6'); assert.equal(r.status, 200); assert.deepEqual(await r.json(), { ac: [] }, 'timeout nespadne');
const worker = (await import('../hlaseni/worker.js')).default;
r = await worker.fetch(new Request('http://x/api/flights?lamin=x'), {}); assert.equal(r.status, 400, 'worker routes /api/flights to the proxy');
console.log('OK: střed z obdélníku, cache, chybné parametry, limit výřezu, výpadek a timeout zdroje, worker');
